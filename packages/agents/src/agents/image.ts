import { z } from 'zod';
import type { Db } from '@cms/db';
import {
  EXTERNAL_DATA_RULES,
  finalizeCost,
  releaseCost,
  reserveCost,
  withIdempotency,
  wrapExternalData,
  type BudgetContext,
} from '@cms/engine';
import type { ImageProvider, ObjectStorage } from '@cms/providers';
import { renderBrandForPrompt } from '../brand.js';
import { genericReview } from '../constructor.js';
import type { NodeExecutor, NodeFile, NodeInput, NodeRender } from '../nodes.js';
import { PLATFORM_LABEL, type Platform } from '../schemas.js';
import {
  json,
  selfModel,
  selfPrompt,
  type AgentContext,
  type AgentResult,
  type AgentSelf,
} from './context.js';

export const ASPECTS = { '4:5': [1080, 1350], '9:16': [1080, 1920], '16:9': [1280, 720] } as const;
export type Aspect = keyof typeof ASPECTS;

export const DEFAULT_ASPECT: Record<Platform, Aspect> = {
  instagram_post: '4:5',
  instagram_carousel: '4:5',
  instagram_reels: '9:16',
  telegram_post: '16:9',
};

/** What the model returns: one image brief per deliverable. */
export const ImageBriefs = z
  .object({
    images: z
      .array(
        z.object({
          deliverableId: z.string(),
          prompt: z.string().min(20).max(1200),
          alt: z.string().min(3).max(300),
          aspect: z.enum(['4:5', '9:16', '16:9']),
        }),
      )
      .min(1)
      .max(10),
  })
  .meta({ title: 'ImageBriefs' });
export type ImageBriefs = z.infer<typeof ImageBriefs>;

export interface GeneratedImageRecord {
  deliverableId: string;
  prompt: string;
  alt: string;
  aspect: Aspect;
  key: string;
  mimeType: string;
  width: number;
  height: number;
  seed: number;
  model: string;
  provider: string;
  costUsd: number;
}

export interface ImageOutput {
  images: GeneratedImageRecord[];
}

export interface ImageAgentDeps {
  db: Db;
  provider: ImageProvider;
  storage: ObjectStorage;
  budget: BudgetContext;
  /** Worst-case price of one image for the budget reservation (0 for the mock). */
  estimateUsd: number;
  /** The agent record that has the capability (its prompt, model and cost line). */
  self: AgentSelf;
}

const CRITERIA = [
  'для каждой единицы контента из плана, которой нужна картинка, есть задание',
  'промпт конкретный и соответствует тексту поста и стилю бренда',
  'на картинке нет текста, логотипов, узнаваемых людей и чужих брендов',
  'соотношение сторон подходит площадке',
];

/**
 * Image (code agent): the model writes image briefs from the plan and the texts, then each
 * image is generated by the ImageProvider (Magnific; mock until the adapter is built) and
 * stored in object storage. Every image is a paid external call: budget reserve -> finalize,
 * idempotency key per run step and image.
 */
export function imageExecutor(d: ImageAgentDeps): NodeExecutor {
  return {
    async run(ctx: AgentContext, input: NodeInput): Promise<AgentResult<ImageOutput>> {
      const prompt = selfPrompt(ctx, d.self);
      const model = selfModel(ctx, d.self, 'worker');
      const parts = [
        `Бриф владельца:\n${input.brief}`,
        `План CEO: ${input.plan.summary}\nЕдиницы контента:\n${json(
          input.plan.deliverables.map((x) => ({
            id: x.id,
            platform: PLATFORM_LABEL[x.platform],
            topic: x.topic,
            aspect: DEFAULT_ASPECT[x.platform],
          })),
        )}`,
      ];
      for (const u of input.upstream)
        parts.push(
          `Результат шага «${u.name}»:\n${wrapExternalData(`step:${u.agent}`, json(u.items))}`,
        );
      if (input.previous != null) {
        const prev = (input.previous as Partial<ImageOutput>).images ?? [];
        parts.push(
          `Прошлые задания:\n${wrapExternalData(
            'previous',
            json(
              prev.map((i) => ({ deliverableId: i.deliverableId, prompt: i.prompt, alt: i.alt })),
            ),
          )}`,
        );
      }
      if (input.ownerComment)
        parts.push(`Комментарий владельца (главное, учти обязательно):\n${input.ownerComment}`);
      if (input.criticIssues.length)
        parts.push(`Замечания проверяющего (исправь):\n${json(input.criticIssues)}`);
      if (input.mode === 'regenerate') parts.push('Сделай заново, с другим визуальным решением.');

      const r = await ctx.llm.callStructured({
        ctx: {
          brandId: ctx.brand.id,
          taskId: ctx.taskId,
          runId: ctx.runId,
          agent: d.self.id,
          promptVersion: prompt.version,
        },
        model,
        system: [
          { text: prompt.text, cache: true },
          { text: renderBrandForPrompt(ctx.brand), cache: true },
          { text: EXTERNAL_DATA_RULES },
        ],
        prompt: parts.join('\n\n'),
        schema: ImageBriefs,
        maxTokens: 4000,
        effort: 'medium',
        idempotencyKey: `${ctx.callKey}:image:${input.step}`,
        ...(ctx.signal ? { signal: ctx.signal } : {}),
      });

      const known = new Set(input.plan.deliverables.map((x) => x.id));
      const briefs = r.output.images.filter((b) => known.has(b.deliverableId));
      if (briefs.length === 0)
        throw new Error('Image: ни одно задание не относится к единицам контента из плана');

      const images: GeneratedImageRecord[] = [];
      let imagesCost = 0;
      for (const [i, b] of briefs.entries()) {
        const key = `${ctx.callKey}:image-gen:${input.step}:${i}`;
        const { result } = await withIdempotency(d.db, key, () => generateOne(d, ctx, b, key));
        images.push(result);
        imagesCost += result.costUsd;
      }
      return {
        output: { images },
        promptVersion: prompt.version,
        model: r.servedModel,
        costUsd: r.costUsd + imagesCost,
      };
    },
    render(output: unknown): NodeRender {
      const o = output as ImageOutput;
      return {
        title: `Картинки: ${o.images.length}`,
        lines: o.images.map(
          (i) => `${i.deliverableId} (${i.aspect}, ${i.width}×${i.height}): ${i.alt}`,
        ),
      };
    },
    files(output: unknown): NodeFile[] {
      return (output as ImageOutput).images.map((i) => ({
        name: `${i.deliverableId}.${i.mimeType === 'image/jpeg' ? 'jpg' : 'png'}`,
        key: i.key,
        mimeType: i.mimeType,
      }));
    },
    review(ctx, input, output, reviewer) {
      // The Critic sees the prompts and descriptions, not the pixels.
      const o = output as ImageOutput;
      return genericReview(
        ctx,
        reviewer,
        input,
        o.images.map(({ deliverableId, prompt, alt, aspect }) => ({
          deliverableId,
          prompt,
          alt,
          aspect,
        })),
        { ...d.self, role: 'задания для картинок к постам', criteria: CRITERIA },
      );
    },
  };
}

async function generateOne(
  d: ImageAgentDeps,
  ctx: AgentContext,
  b: ImageBriefs['images'][number],
  key: string,
): Promise<GeneratedImageRecord> {
  const [width, height] = ASPECTS[b.aspect];
  const reservation = await reserveCost(d.db, d.budget, {
    brandId: ctx.brand.id,
    taskId: ctx.taskId,
    runId: ctx.runId,
    agent: d.self.id,
    kind: 'image',
    provider: d.provider.name,
    model: 'image',
    estimateUsd: d.estimateUsd,
    idempotencyKey: `${key}:cost`,
  });
  try {
    const img = await d.provider.generate({ prompt: b.prompt, width, height });
    const ext = img.mimeType === 'image/jpeg' ? 'jpg' : 'png';
    const objectKey = `images/${ctx.taskId}/${ctx.runId ?? 'test'}-${b.deliverableId}-${img.seed}.${ext}`;
    await d.storage.put(objectKey, img.data, img.mimeType);
    // The mock costs nothing; the real adapter reports its price (TODO(verify) with Magnific docs).
    const costUsd = img.provider === 'mock' ? 0 : d.estimateUsd;
    await finalizeCost(d.db, reservation.id, {
      costUsd,
      model: img.model,
      estimated: img.provider !== 'mock',
      units: 1,
    });
    return {
      deliverableId: b.deliverableId,
      prompt: b.prompt,
      alt: b.alt,
      aspect: b.aspect,
      key: objectKey,
      mimeType: img.mimeType,
      width: img.width,
      height: img.height,
      seed: img.seed,
      model: img.model,
      provider: img.provider,
      costUsd,
    };
  } catch (err) {
    await releaseCost(d.db, reservation.id);
    throw err;
  }
}
